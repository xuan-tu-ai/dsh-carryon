#!/usr/bin/env node
// Generate web-preset.patch.yml: the "CarryOn mode" agent preset for dsh's web profile.
//
// dsh's web profile mounts compaction inside each agent preset, and an external bundle cannot patch rows inside
// a preset (docs/p0-findings.md). So this bundle ships its own preset: a copy of dsh-web-app's `standard`
// preset whose compaction group mounts dsh-carryon instead of compaction-basic. The copy is generated from the
// dsh-web-app release pinned in package.json (`engines.dsh`), so updating dsh means re-running this script.
//
// Usage: node scripts/gen-web-preset.mjs           write web-preset.patch.yml
//        node scripts/gen-web-preset.mjs --check   exit 1 if the committed file is out of date
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'web-preset.patch.yml')
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const DSH_VERSION = pkg.devDependencies['@deepseek-ai/dsh-compaction-basic']
const WEB_APP = `@deepseek-ai/dsh-web-app@${DSH_VERSION}`

/** Bundle detection shared by the bundle's patch files: true in profiles built on dsh-web-app (web, desktop). */
export const WEB_PROFILE_EXPR = "ctx.get('profileContext')?.startedBundles?.includes('@deepseek-ai/dsh-web-app') === true"

function fetchStandardPreset() {
  const dir = mkdtempSync(join(tmpdir(), 'dsh-web-app-'))
  try {
    const tarball = execFileSync('npm', ['pack', WEB_APP, '--silent', '--pack-destination', dir], { encoding: 'utf8' }).trim()
    execFileSync('tar', ['-xzf', join(dir, tarball), '-C', dir, 'package/presets/standard.patch.yml'])
    return readFileSync(join(dir, 'package/presets/standard.patch.yml'), 'utf8')
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

/** Replace `from` with `to`, requiring exactly one occurrence so an upstream change fails loudly. */
function replaceOnce(text, from, to) {
  const count = text.split(from).length - 1
  if (count !== 1) throw new Error(`expected exactly one match for ${JSON.stringify(from)}, found ${count}`)
  return text.replace(from, to)
}

function generate(standard) {
  const body = standard.slice(standard.indexOf('- insert:'))
  let out = replaceOnce(body, '    - id: preset-standard\n      name: \'@deepseek-ai/dsh-agent-preset\'\n',
    '    - id: preset-carryon\n      name: \'@deepseek-ai/dsh-agent-preset\'\n'
    + `      disabled: !!js "!(${WEB_PROFILE_EXPR})"\n`)
  out = replaceOnce(out, '        id: standard\n        order: 1\n',
    '        id: carryon\n'
    + '        name: CarryOn mode\n'
    + '        description: Standard mode with CarryOn context folding (dsh-carryon, experimental).\n'
    + '        order: 0\n')
  out = replaceOnce(out, "              - id: compaction-basic\n                name: '@deepseek-ai/dsh-compaction-basic'\n",
    '              - id: carryon-compaction\n                name: dsh-carryon\n')
  const header = [
    '# GENERATED by scripts/gen-web-preset.mjs from ' + WEB_APP + ' presets/standard.patch.yml. Do not edit.',
    '#',
    '# "CarryOn mode": dsh\'s standard agent preset with dsh-carryon as its compaction backend. Only enabled in',
    '# profiles built on dsh-web-app (web, desktop), where compaction lives inside agent presets.',
  ].join('\n')
  return `${header}\n${out}`
}

const generated = generate(fetchStandardPreset())
if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8')
  if (current !== generated) {
    console.error(`web-preset.patch.yml is out of date with ${WEB_APP}; run node scripts/gen-web-preset.mjs`)
    process.exit(1)
  }
  console.log(`web-preset.patch.yml matches ${WEB_APP}`)
} else {
  writeFileSync(OUT, generated)
  console.log(`wrote web-preset.patch.yml from ${WEB_APP}`)
}
